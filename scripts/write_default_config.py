"""Regenerate configs/default.toml from the dataclass defaults in src.config."""

from dataclasses import fields
from pathlib import Path

from src.config import PipelineConfig


def value(item):
    if isinstance(item, bool):
        return "true" if item else "false"
    if isinstance(item, str):
        return f'"{item}"'
    if isinstance(item, tuple):
        return "[" + ", ".join(value(x) for x in item) + "]"
    return repr(item)


def main() -> None:
    config = PipelineConfig()
    lines = ["# spacegen defaults, generated by scripts/write_default_config.py.", ""]
    for section in fields(config):
        lines.append(f"[{section.name}]")
        values = getattr(config, section.name)
        lines += [f"{f.name} = {value(getattr(values, f.name))}" for f in fields(values)]
        lines.append("")
    path = Path(__file__).resolve().parents[1] / "configs" / "default.toml"
    path.write_text("\n".join(lines))
    if PipelineConfig.from_toml(path) != config:
        raise SystemExit("default.toml does not round-trip")


if __name__ == "__main__":
    main()
